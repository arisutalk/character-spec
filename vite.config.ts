/// <reference types="vitest/config" />
import { readdirSync, statSync } from "node:fs";
import { relative, resolve } from "node:path";

import { defineConfig } from "vite";
import dts from "vite-plugin-dts";

/**
 * The entries of the package under `src/types`:
 * - the public barrel of each spec version (`v0/index.ts` becomes `v0`)
 * - every schema module (`v0/Character/Character.ts` becomes `v0/Character/Character`)
 *
 * The barrels of the folders inside a version (`v0/Character/index.ts`) are not
 * entries: nobody can import them, so they are inlined into the version barrel.
 */
function getEntries(
    dir: string,
    baseDir: string = dir,
): Record<string, string> {
    const entries: Record<string, string> = {};
    const files = readdirSync(dir);

    for (const file of files) {
        const fullPath = resolve(dir, file);
        const stat = statSync(fullPath);

        if (stat.isDirectory()) {
            Object.assign(entries, getEntries(fullPath, baseDir));
        } else if (
            stat.isFile() &&
            file.endsWith(".ts") &&
            !file.endsWith(".d.ts")
        ) {
            const relativePath = relative(baseDir, fullPath).replaceAll(
                "\\",
                "/",
            );
            const isBarrel = file === "index.ts";
            if (isBarrel && !/^v\d+\/index\.ts$/.test(relativePath)) continue;

            entries[relativePath.replace(/\.ts$/, "").replace(/\/index$/, "")] =
                fullPath;
        }
    }

    return entries;
}

const typeEntries = getEntries(resolve(import.meta.dirname, "src/types"));

/**
 * Intermediate declarations emitted by tsc. They carry the precise zod types of
 * every schema, which `scripts/generate-types.ts` merges with the JSDoc-rich
 * types it generates. They are not part of the package, so they stay out of `dist`.
 */
const DTS_CACHE_DIR = "node_modules/.cache/character-spec-dts";

const dtsConfig = dts({
    include: ["src/**/*.ts"],
    exclude: ["**/*.test.ts", "**/*.spec.ts"],
    tsconfigPath: "./tsconfig.main.json",
    entryRoot: "src",
    outDirs: DTS_CACHE_DIR,
    compilerOptions: { declarationMap: false },
});

export default defineConfig({
    plugins: [
        // Types for src/types are generated by scripts/generate-types.ts using zod-to-ts
        // dts plugin emits the intermediate declarations that script builds upon
        dtsConfig,
    ],
    build: {
        lib: {
            entry: {
                index: "src/index.ts",
                utils: "src/utils.ts",
                ...typeEntries,
            },
            fileName: (_, entryName) => `${entryName}.js`,

            formats: ["es"],
        },
        sourcemap: true,
        rolldownOptions: {
            external: ["zod"],
        },
    },
    test: {
        environment: "node",
    },
    resolve: {
        // `@/` of src and tests. Vite follows the tsconfig references.
        tsconfigPaths: true,
    },
    clearScreen: false,
});
